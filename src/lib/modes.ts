const MODE_IDS = new Set<string>(MODE_PRESETS.map((preset) => preset.id));

export function isBoardMode(value: unknown): value is BoardMode {
  return typeof value === "string" && MODE_IDS.has(value);
}

/** 知らない値・未設定は雑談として扱う（モードが無かった頃のボードもそのまま動く） */
export function parseMode(value: unknown): BoardMode {
  return isBoardMode(value) ? value : DEFAULT_MODE;
}

export function modePreset(mode: BoardMode | undefined): ModePreset {
  return MODE_PRESETS.find((preset) => preset.id === mode) ?? MODE_PRESETS[0]!;
}

export function boardMode(board: Pick<Board, "mode"> | undefined): BoardMode {
  return parseMode(board?.mode);
}

/** ボードの用途を付け替える（雑談は項目ごと消して、保存データを昔の形のままにする） */
export function withMode<T extends Pick<Board, "mode">>(board: T, mode: BoardMode): T {
  const next = { ...board };
  if (mode === DEFAULT_MODE) delete next.mode;
  else next.mode = mode;
  return next;
}

/**
 * みんなのトピック図鑑・人気の話題に混ぜてよいモードか。
 * 雑談以外は個人的な内容になりやすく、雑談の図鑑の質も下がるので、端末の外へ送らない。
 */
export function sharesKnowledge(mode: BoardMode | undefined): boolean {
  return parseMode(mode) === "chat";
}

export function pickModeStarter(mode: BoardMode, exclude: string[] = []): string | null {
  const starters = modePreset(mode).starters;
  if (starters.length === 0) return null;
  const pool = starters.filter((topic) => !exclude.includes(topic));
  const source = pool.length > 0 ? pool : starters;
  return source[Math.floor(Math.random() * source.length)]!;
}

/** AI への指示（お題・話の流れ・重複しない語の部分は gemini-core が組み立てる） */
export function buildModePrompt(mode: BoardMode, seed: string, count: number, flow: string, banned: string): string {
  const { prompt } = modePreset(mode);
  const example = prompt.example
    ? `
例: お題「${prompt.example.seed}」なら
よい: ${JSON.stringify(prompt.example.good)}
よくない: ${JSON.stringify(prompt.example.bad)}
`
    : "";
  return `あなたは${prompt.role}です。
お題「${seed}」から、${prompt.ask}をちょうど${count}個出してください。
${flow}
よい切り口:
${prompt.rules.map((rule) => `- ${rule}`).join("\n")}
${example}
条件:
- 日本語のみ
- 各キーワードは2〜${LABEL_MAX}文字の短い名詞句
- 番号・箇条書き記号・説明・引用符・Markdown・コードフェンスは付けない
- お題そのものは繰り返さない
- 次と重複しない: ${banned}

出力は JSON 配列だけ。要素はちょうど${count}個。前後に文字を付けない。
例: ["キーワード1","キーワード2","キーワード3","キーワード4","キーワード5","キーワード6","キーワード7","キーワード8"]`;
}
