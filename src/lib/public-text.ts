/**
 * ほかの人に見える所（トピック図鑑・ホームの人気のお題・みんなが作った話題マップ）に出してよい文か。
 * 自分のボードの中では何を書いてもよく、ここで止めるのは公開するときだけ。
 *
 * 規制しすぎない: 「死にたい」「消えたい」のような重い悩みや、名前の出ない愚痴（「元カレがクズだった」）は通す。
 * 止めるのは、個人につながる書き方と、他人に向けた暴言・晒しの呼びかけ・よく知られた差別語だけ。
 * 普通の言葉で実名を書かれたものは文字では見分けられないので、topic-archive-data.ts で手作業で隠す。
 */

/** 連絡先・URL・@ハンドル・住所・ID の書き方など、個人につながりそうな文字列 */
const PERSONAL_PATTERNS = [
  // URL・メール・@ハンドル・電話・長い数字・郵便番号
  /(https?:\/\/|www\.|[\w.+-]+@[\w-]+\.|@[A-Za-z0-9_]{3,}|\d{2,4}-\d{2,4}-\d{3,4}|\d{10,}|〒\s*\d{3}-?\d{4})/u,
  // 住所（「3丁目5」「123番地」「2番5号」「渋谷区神南1-2-3」）
  /\d{1,4}丁目\s*\d|\d{1,5}番地|\d{1,4}番\s*\d{1,4}号|[都道府県市区町村郡][^\d\s]{1,10}\d{1,4}-\d{1,4}/u,
  // ID の書き方（「ID: taro_1234」「ユーザー名はhanako99」「mike#1234」）
  /(?:ID|アカウント名|ユーザー名|ユーザ名)\s*[:：は]?\s*[A-Za-z0-9_.-]{4,}|[A-Za-z0-9_.]{2,32}#\d{4}\b/iu,
];

export function looksPersonal(text: string): boolean {
  const normalized = text.normalize("NFKC");
  return PERSONAL_PATTERNS.some((pattern) => pattern.test(normalized));
}

/**
 * 他人を傷つける言葉。カタカナはひらがなに寄せ、空白・区切りを詰めてから見る（「死 ね」「キチガイ」も拾う）。
 * 同じ文字を含む普通の語（「死ねない」「シネマ」「支那そば」「ちょんまげ」「土人形」）は外している。
 */
const ABUSIVE_PATTERNS = [
  // 他人に向けた暴言・脅し（「死にたい」「死ねない」「死ねば」は通す）
  /死ね(?![ばなずるた])|氏ね|たひね|しねよ|自殺しろ|首(?:吊|つ)れ(?![なるた])|死んでくれ|死んでしまえ(?!ば)/u,
  /殺すぞ|ころすぞ|殺してやる|ころしてやる|ぶっ殺|ぶっころ|消えろ|失せろ|くたばれ/u,
  // 晒し・特定・凸の呼びかけ（「晒された」「特定された」のような被害の話は通す）
  /(?:住所|本名|顔|素顔|個人情報|自宅|家|職場|学校|勤務先|垢|アカウント)(?:を|も)?(?:晒[すそせ]|さら[すそせ])/u,
  /晒そう|晒せ(?![るば])|晒してやる|晒し上げ|晒しあげ|晒しすれ/u,
  /(?:住所|本名|顔|身元|自宅|家|職場|学校|勤務先|中の人)(?:を|の)?特定(?:しよう|してやる|する|したい|班)|特定班|特定厨/u,
  /(?:電|鬼|自宅|家)凸|凸(?:しよう|してやる|ろう)/u,
  // よく知られた差別語
  /きちがい|気違い|基地外(?!\p{Script=Han})|がいじ(?!ん)|池沼|害児|知恵遅れ|かたわ(?!ら)|つんぼ/u,
  /ちょん(?:公|こう|ころ|国|人)|支那(?:人|畜|豚|ちく)|(?<!郷)土人(?!形|気)|にがー|nigg(?:er|a)|faggot|chink/u,
];

function forCheck(text: string): string {
  return text
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ァ-ヶ]/gu, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .replace(/[\s​・.,、。_*＊\-]/gu, "");
}

export function looksAbusive(text: string): boolean {
  const normalized = forCheck(text);
  return ABUSIVE_PATTERNS.some((pattern) => pattern.test(normalized));
}

/** ほかの人に見える所に出してよいか */
export function isPublicSafe(text: string): boolean {
  return !looksPersonal(text) && !looksAbusive(text);
}

